"""PlatformIO pre-build script: turns the ASCII JSON folders into src/art_data.h.

  ascii/*.json            -> ASCII_PIECES   (tap cycles through them, by file name)
  gestures/shake/*.json   -> SHAKE_PIECES   (played when the device is shaken)

JSON format (ascii-animation/v1): "frames": [{"ascii": "...", "duration_ms": N}, ...]
and optional "ascii_size": {"cols": N, "rows": N}. If ascii_size is missing the
size is measured from the frames. The header is only rewritten when its content
changes, so unchanged builds stay incremental.
"""
import json
import os
import re

try:
    Import("env")  # noqa: F821  (provided by PlatformIO)
    PROJECT_DIR = env["PROJECT_DIR"]  # noqa: F821
except NameError:
    PROJECT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

OUT = os.path.join(PROJECT_DIR, "src", "art_data.h")
GROUPS = [
    ("ASCII", os.path.join(PROJECT_DIR, "ascii")),
    ("SHAKE", os.path.join(PROJECT_DIR, "gestures", "shake")),
]
DEFAULT_MS = 100


def load_piece(path):
    with open(path, encoding="utf-8") as f:
        doc = json.load(f)
    frames = []
    for fr in doc["frames"]:
        art = fr["ascii"].replace("\r\n", "\n").rstrip("\n")
        frames.append((art, int(fr.get("duration_ms", DEFAULT_MS))))
    if not frames:
        raise ValueError("%s has no frames" % path)
    size = doc.get("ascii_size") or {}
    cols = int(size.get("cols") or max(len(l) for a, _ in frames for l in a.split("\n")))
    rows = int(size.get("rows") or max(a.count("\n") + 1 for a, _ in frames))
    return frames, cols, rows


def ident(name):
    return re.sub(r"\W", "_", name)


def generate():
    out = ["// GENERATED by tools/embed_art.py from ascii/ and gestures/ -- do not edit.",
           "#pragma once", "",
           "struct Frame { const char* art; uint16_t ms; };",
           "struct Piece { const char* name; const Frame* frames; int count; int cols; int rows; };", ""]
    for group, folder in GROUPS:
        files = sorted(f for f in os.listdir(folder) if f.lower().endswith(".json")) if os.path.isdir(folder) else []
        names = []
        for fn in files:
            frames, cols, rows = load_piece(os.path.join(folder, fn))
            var = "%s_%s" % (group.lower(), ident(os.path.splitext(fn)[0]))
            out.append("static const Frame %s[] = {" % var)
            for art, ms in frames:
                assert ')ART"' not in art
                out.append('{R"ART(%s)ART", %d},' % (art, ms))
            out.append("};")
            names.append((os.path.splitext(fn)[0], var, len(frames), cols, rows))
        out.append("static const Piece %s_PIECES[%d] = {" % (group, max(1, len(names))))
        for n, var, cnt, cols, rows in names:
            out.append('  {"%s", %s, %d, %d, %d},' % (n, var, cnt, cols, rows))
        if not names:
            out.append('  {"", nullptr, 0, 0, 0},')
        out.append("};")
        out.append("static const int %s_COUNT = %d;" % (group, len(names)))
        out.append("")
    text = "\n".join(out)
    old = None
    if os.path.exists(OUT):
        with open(OUT, encoding="utf-8") as f:
            old = f.read()
    if old != text:
        with open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("embed_art: wrote %s" % OUT)


generate()
